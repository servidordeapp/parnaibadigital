import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

const PACKAGE_DIR = fileURLToPath(new URL("..", import.meta.url));
const GENERATED = fileURLToPath(new URL("../src/generated/api-v1.ts", import.meta.url));

/**
 * Cenário V11 — o contrato é a fonte de verdade (D-10, Princípio VII).
 *
 * O arquivo gerado é versionado, o que é conveniente (ninguém precisa rodar o gerador para
 * abrir o projeto) mas cria um risco real: alguém edita o OpenAPI e esquece de regerar, ou
 * — pior — edita o arquivo gerado à mão para "consertar" um tipo. Este teste regenera e
 * compara: qualquer divergência reprova.
 */
describe("tipos gerados do contrato OpenAPI", () => {
  it("declara na primeira linha que é gerado — edição à mão não é caminho", () => {
    expect(readFileSync(GENERATED, "utf8")).toContain("auto-generated by openapi-typescript");
  });

  it("está em sincronia com contracts/openapi-v1.yaml (cenário V11)", () => {
    const committed = readFileSync(GENERATED, "utf8");

    const regenerated = execFileSync(
      "pnpm",
      [
        "exec",
        "openapi-typescript",
        "../../specs/001-fundacao-prototipo-monorepo/contracts/openapi-v1.yaml",
        "--root-types",
      ],
      { cwd: PACKAGE_DIR, encoding: "utf8", maxBuffer: 32 * 1024 * 1024 },
    );

    expect(regenerated.trim()).toBe(committed.trim());
  }, 120_000);
});
